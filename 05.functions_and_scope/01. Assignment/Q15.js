function averageOfTwo(x, y) {
    return (x + y) / 2
};

console.log(averageOfTwo(96, 98));

//3.
function maxOfTwo(a, b) {
    if (a > b) {
        return a
    } else {
        return b
    }
};

console.log(maxOfTwo(97, 89));

